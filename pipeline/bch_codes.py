"""Code families compared in step 4 (extended BCH, Golay), built from first principles.

GF(2^m) arithmetic, minimal polynomials and generator polynomials are computed
here (not taken from tables); every code's minimum distance is then established
by exhaustive search -- codeword enumeration when k <= 22, otherwise a search
over parity-check column subsets -- so the delivered capacity t = (d-1)//2 is a
measured property of the code, not a quoted one.
"""
import itertools
import math

import numpy as np

PRIM = {3: 0b1011, 4: 0b10011, 5: 0b100101, 6: 0b1000011, 7: 0b10000011}
GOLAY_G = (1 << 11) | (1 << 10) | (1 << 6) | (1 << 5) | (1 << 4) | (1 << 2) | 1


def _gf(m):
    N = 2 ** m - 1
    exp = [0] * (2 * N); log = [0] * (N + 1); x = 1
    for i in range(N):
        exp[i] = x; log[x] = i
        x <<= 1
        if x >> m:
            x ^= PRIM[m]
    for i in range(N, 2 * N):
        exp[i] = exp[i - N]
    return exp, log, N


def minpoly(i, m):
    exp, log, N = _gf(m)
    conj, e = [], i % N
    while e not in conj:
        conj.append(e); e = (2 * e) % N
    poly = [1]
    for c in conj:
        r = exp[c]; new = [0] * (len(poly) + 1)
        for j, a in enumerate(poly):
            new[j + 1] ^= a
            new[j] ^= 0 if a == 0 else exp[log[a] + log[r]]
        poly = new
    assert all(a in (0, 1) for a in poly)
    return sum(a << j for j, a in enumerate(poly))


def pmul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a <<= 1; b >>= 1
    return r


def bch_generator(m, t):
    seen, g = set(), 1
    for i in range(1, 2 * t + 1):
        mp = minpoly(i, m)
        if mp not in seen:
            seen.add(mp); g = pmul(g, mp)
    return g


def _parity_bit(x):
    return bin(x).count("1") & 1


def min_distance(rows, n):
    """Exact minimum distance of the binary linear code spanned by `rows`
    (integers, bit j = coordinate j), length n."""
    k = len(rows)
    if k <= 22:
        cw = np.zeros(1, dtype=np.uint64)
        for r in rows:
            cw = np.concatenate([cw, cw ^ np.uint64(r)])
        return int(np.bitwise_count(cw[1:]).min())
    # high rate: d = fewest parity-check columns summing to zero
    G = np.array([[(r >> j) & 1 for j in range(n)] for r in rows], dtype=np.uint8)
    # systematic form over GF(2)
    G = G.copy(); piv = []
    rr = 0
    for c in range(n):
        p = next((i for i in range(rr, k) if G[i, c]), None)
        if p is None:
            continue
        G[[rr, p]] = G[[p, rr]]
        for i in range(k):
            if i != rr and G[i, c]:
                G[i] ^= G[rr]
        piv.append(c); rr += 1
        if rr == k:
            break
    free = [c for c in range(n) if c not in piv]
    # H columns: for pivot column piv[i], syndrome bits = G[i, free]; for free col j, unit vector
    cols = [0] * n
    for i, c in enumerate(piv):
        cols[c] = int("".join(str(int(b)) for b in G[i, free][::-1]), 2)
    for jj, c in enumerate(free):
        cols[c] = 1 << jj
    for w in range(1, n + 1):
        for comb in itertools.combinations(range(n), w):
            s = 0
            for c in comb:
                s ^= cols[c]
            if s == 0:
                return w
    return None


def shortened_cyclic(g, n):
    """Rows of the length-n shortening of the cyclic code generated by g."""
    r = g.bit_length() - 1
    return [g << i for i in range(n - r)]


def shortened_extended(g, N, n):
    """Extend the length-N cyclic code generated by g with an overall parity bit,
    then shorten to length n (parity bit kept, information positions removed)."""
    r = g.bit_length() - 1
    rows = []
    for i in range(n - 1 - r):
        c = g << i
        rows.append(c | (_parity_bit(c) << (n - 1)))
    return rows


def code(name, rows, n):
    k = len(rows)
    d = min_distance(rows, n)
    return {"name": f"{name} [{n},{k},{d}]", "n": n, "k": k, "parity": n - k, "d": d, "t": (d - 1) // 2}


def alternative_codes(n):
    """Codes the paper's m=ceil(log2(n+1)) shortened-BCH rule does not reach."""
    out = []
    if n in (16, 32):                                      # extended BCH, length 2^m
        m = int(math.log2(n)); N = n - 1
        seen = set()
        for t in range(1, N // 2 + 1):
            g = bch_generator(m, t)
            if g in seen or g.bit_length() - 1 >= N:
                continue
            seen.add(g)
            c = code(f"extended BCH (from BCH({N}))", shortened_extended(g, N, n), n)
            out.append(dict(c, family="extended BCH"))
    if n == 24:                                            # extended BCH(32) shortened to 24
        seen = set()
        for t in range(1, 16):
            g = bch_generator(5, t)
            if g in seen or g.bit_length() - 1 + 1 >= n:
                continue
            seen.add(g)
            c = code("extended BCH (from BCH(31)), shortened to 24", shortened_extended(g, 31, n), n)
            out.append(dict(c, family="extended BCH (shortened from 32)"))
        out.append(dict(code("extended Golay", shortened_extended(GOLAY_G, 23, 24), 24),
                        family="extended Golay"))
    if n == 23:
        out.append(dict(code("Golay", shortened_cyclic(GOLAY_G, 23), 23), family="Golay"))
    return out
